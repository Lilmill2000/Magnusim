// The Magnusim CAD export's self-check (scripts/export-cad-repo/self-check.mjs): the words that
// say a file was written with an AI coding tool, which no text file of the copy may hold, even
// wrapped onto the next comment line; and the product's own words about the agents its
// Assistant drives, which stay allowed.
// SPDX-License-Identifier: GPL-3.0-or-later
import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { aiAuthorship } from '../export-cad-repo/self-check.mjs';

const found = (text) => aiAuthorship(text).map((m) => m.found.replace(/\s+/g, ' '));

describe('aiAuthorship', () => {
  test("finds an AI tool's skill or notes cited as a source, wrapped onto the next comment line", () => {
    const block = ' * The 1M-token context: the "Current Models" table of the claude-api\n * skill\'s model reference (read 2026-10-29), Opus 5.5';
    assert.deepEqual(found(block), ['claude-api * skill', "skill's model reference"]);
    const line = '  // Read again: the pricing page says $0.30, where the claude-api\n  // skill\'s model notes (cached 2026-10-06) say $0.20.';
    assert.deepEqual(found(line), ['claude-api // skill', "skill's model notes"]);
  });

  test('finds "generated by" AI, "AI-generated", a coding tool used to write it, and the tell-tale phrase of a chat model', () => {
    assert.deepEqual(found('// This file was generated by ChatGPT.'), ['generated by ChatGPT']);
    assert.deepEqual(found('# Drafted using Copilot, then edited'), ['Drafted using Copilot']);
    assert.deepEqual(found('Written with an AI\n// assistant'), ['Written with an AI']);
    assert.deepEqual(found('// generated by AI, checked by hand'), ['generated by AI']);
    assert.deepEqual(found('produced via LLMs'), ['produced via LLMs']);
    assert.deepEqual(found('/* AI-generated */ const x = 1;'), ['AI-generated']);
    assert.deepEqual(found('LLM-assisted port of the C code'), ['LLM-assisted']);
    assert.deepEqual(found('// written with Claude\n// Code, then tidied'), ['written with Claude // Code']);
    assert.deepEqual(found('created using Cursor'), ['created using Cursor']);
    assert.deepEqual(found('generated with GPT-4o'), ['generated with GPT-4o']);
    assert.deepEqual(found('// Copilot wrote the first draft'), ['Copilot wrote']);
    assert.deepEqual(found('see https://chatgpt.com/share/abc and https://claude.ai/chat/def'), ['chatgpt.com/share/', 'claude.ai/chat/']);
    assert.deepEqual(found('As an AI language model, I cannot'), ['As an AI language model']);
    assert.deepEqual(found('authored by an LLM'), ['authored by an LLM']);
  });

  test("leaves the product's own words about agents, models, tools and what the Assistant makes alone", () => {
    for (const text of [
      'Claude Code and Codex are coding agents the Assistant can drive.',
      "  skill: 'deny',",
      'The OpenAI provider sends the request.',
      'a reply generated by the model',
      'the text written by the agent',
      'the page is generated with esbuild',
      'written by a person, generated by an aide',
      'an AI Assistant that uses the same tools you do',
      'a sketch created by the Assistant, or created by the AI in a turn',
      'the reply Codex sends, generated by Claude Code',
      'an AI-free build; the AI generated three bodies',
      'https://docs.claude.com/en/docs/about-claude/models',
    ]) assert.deepEqual(found(text), [], text);
  });
});
