// The copies of the generated workspace SDK types (scripts/plugin-sdk-copies.mjs):
// CAD's is one of them and holds the generated text, a stale or missing copy is
// named for `npm run gen:plugin-sdk:check`, and a CRLF checkout of the same text
// is current.
// SPDX-License-Identifier: GPL-3.0-or-later
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { copyPath, staleCopies, WORKSPACE_DTS_COPIES } from '../plugin-sdk-copies.mjs';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CAD_COPY = 'bundled-plugins/cad/src/types/workspace-sdk.d.ts';
const lf = (text) => text.replace(/\r\n/g, '\n');

describe('the generated workspace SDK types have copies the generator keeps current', () => {
  it("CAD's src/types/workspace-sdk.d.ts is one of them", () => {
    assert.ok(WORKSPACE_DTS_COPIES.includes(CAD_COPY));
    for (const rel of WORKSPACE_DTS_COPIES) assert.match(rel, /^[a-z0-9_-]+(\/[A-Za-z0-9_.-]+)+\.d\.ts$/, rel);
  });

  it('every copy in this repo holds the text of docs/plugins/workspace-sdk.d.ts', () => {
    const generated = lf(readFileSync(join(WEB, 'docs', 'plugins', 'workspace-sdk.d.ts'), 'utf8'));
    assert.match(generated, /Generated by `npm run gen:plugin-sdk` from src\/plugin-sdk\/workspace\.ts\. Do not edit\./);
    assert.deepEqual(staleCopies(WEB, WORKSPACE_DTS_COPIES, generated), []);
    for (const rel of WORKSPACE_DTS_COPIES) assert.equal(lf(readFileSync(copyPath(WEB, rel), 'utf8')), generated, rel);
  });

  it('names a missing copy and one whose text differs, and not a CRLF checkout of the same text', () => {
    const root = mkdtempSync(join(tmpdir(), 'magnusim-sdk-copies-'));
    try {
      const text = "declare module '@magnusim/workspace' {\n  export const SDK_VERSION: string;\n}\n";
      const put = (rel, body) => {
        mkdirSync(dirname(copyPath(root, rel)), { recursive: true });
        writeFileSync(copyPath(root, rel), body);
      };
      put('a/types/same.d.ts', text);
      put('b/types/crlf.d.ts', text.replace(/\n/g, '\r\n'));
      put('c/types/old.d.ts', text.replace('SDK_VERSION', 'OLD_VERSION'));
      put('d/types/short.d.ts', text.trimEnd());
      const copies = ['a/types/same.d.ts', 'b/types/crlf.d.ts', 'c/types/old.d.ts', 'd/types/short.d.ts', 'e/types/missing.d.ts'];
      assert.deepEqual(staleCopies(root, copies, text), ['c/types/old.d.ts', 'd/types/short.d.ts', 'e/types/missing.d.ts']);
      assert.deepEqual(staleCopies(root, [], text), []);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('places a copy under the web root by its /-separated path', () => {
    assert.equal(copyPath(WEB, CAD_COPY), join(WEB, 'bundled-plugins', 'cad', 'src', 'types', 'workspace-sdk.d.ts'));
  });
});
