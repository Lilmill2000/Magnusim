/**
 * Generate src/api/registry.gen.ts from the committed registry dump.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dump = JSON.parse(readFileSync(join(root, 'scripts/generated/registry.json'), 'utf8'));

function keysOf(kind) {
  const bag = dump[kind] || dump[`${kind}s`] || [];
  if (Array.isArray(bag)) return bag.map((row) => row.key).filter(Boolean);
  return Object.keys(bag);
}

const analysis = keysOf('analysis');
const filters = keysOf('filter');
const meshers = keysOf('mesher');
const materials = keysOf('material');
const bcs = keysOf('bc');
const monitors = keysOf('monitor');

const q = (xs) => xs.map((k) => `'${k}'`).join(' | ') || 'string';

const body = `/* Generated by scripts/gen-registry-types.mjs — do not edit by hand. */
export type AnalysisKey = ${q(analysis)};
export type FilterKey = ${q(filters)};
export type MesherKey = ${q(meshers)};
export type MaterialKey = ${q(materials)};
export type BcKey = ${q(bcs)};
export type MonitorKey = ${q(monitors)};

export interface RegistryRow {
  key: string;
  label: string;
  plugin?: string;
  schema?: Record<string, unknown> | null;
  numerics_schema?: Record<string, unknown> | null;
  control_schema?: Record<string, unknown> | null;
  settings_schema?: Record<string, unknown> | null;
  params_schema?: Record<string, unknown> | null;
  category?: string;
  time_dependency?: string;
  default_turbulence?: string;
  default_solver?: string;
  turbulence_models?: string[];
}

export interface RegistryDescribe {
  analysis?: RegistryRow[];
  filter?: RegistryRow[];
  mesher?: RegistryRow[];
  material?: RegistryRow[];
  bc?: RegistryRow[];
  monitor?: RegistryRow[];
  plugins?: Array<Record<string, unknown>>;
}
`;

writeFileSync(join(root, 'src/api/registry.gen.ts'), body);
console.log('wrote src/api/registry.gen.ts');
